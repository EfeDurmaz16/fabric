#!/bin/sh
# Proves that scripts/check-hygiene.sh fires. A gate that greps for a pattern
# fails silently when the pattern stops matching, so each named failure mode
# below is a case that must exit nonzero, and the clean tree must exit zero.
#
# Usage: scripts/test-check-hygiene.sh
set -eu

script=$(cd "$(dirname "$0")" && pwd)/check-hygiene.sh
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

em_dash=$(printf '\342\200\224')
failures=0

# A fresh repository with one clean commit on main.
new_repo() {
  rm -rf "$work/repo"
  mkdir -p "$work/repo/sub"
  git -C "$work/repo" init -q -b main
  git -C "$work/repo" config user.name test
  git -C "$work/repo" config user.email test@example.invalid
  git -C "$work/repo" config commit.gpgsign false
  printf 'No Co-Authored-By, no "Generated with" lines, no generated-by footers.\n' > "$work/repo/sub/ADR.md"
  git -C "$work/repo" add .
  git -C "$work/repo" commit -q -m 'docs: state the rule' -m 'No Co-Authored-By, no "Generated with", no AI attribution anywhere.'
  git -C "$work/repo" branch -q base
}

# Adds a tracked file with the given content and commits it with the given
# subject and body.
commit() {
  printf '%s\n' "$1" > "$work/repo/note.txt"
  git -C "$work/repo" add note.txt
  git -C "$work/repo" commit -q -m "$2" -m "$3"
}

expect() {
  want=$1
  name=$2
  dir=$3
  shift 3
  if (cd "$dir" && "$script" "$@") > /dev/null 2>&1; then
    got=pass
  else
    got=fail
  fi
  if [ "$got" = "$want" ]; then
    echo "ok   $name"
  else
    echo "FAIL $name: expected $want, got $got" >&2
    failures=$((failures + 1))
  fi
}

new_repo
commit 'plain text' 'docs: add a note' 'Nothing special.'
expect pass 'clean tree, rule-naming prose in a file and a commit' "$work/repo" base

new_repo
commit "a ${em_dash} b" 'docs: add a note' 'Nothing special.'
expect fail 'em dash in a tracked file' "$work/repo" base
expect fail 'em dash in a tracked file, run from a subdirectory' "$work/repo/sub" base

new_repo
commit 'Co-authored-by: Someone <someone@example.invalid>' 'docs: add a note' 'Nothing special.'
expect fail 'co-authored-by trailer in a tracked file, canonical casing' "$work/repo" base

new_repo
commit 'Generated with Some Tool' 'docs: add a note' 'Nothing special.'
expect fail 'generated-with line in a tracked file, no link' "$work/repo" base

new_repo
commit 'plain text' 'docs: add a note' "a ${em_dash} b"
expect fail 'em dash in a commit message' "$work/repo" base

new_repo
commit 'plain text' 'docs: add a note' 'Co-Authored-By: Someone <someone@example.invalid>'
expect fail 'co-authored-by trailer in a commit message' "$work/repo" base

new_repo
commit 'plain text' 'docs: add a note' 'Generated with [Some Tool](https://example.invalid)'
expect fail 'generated-with trailer in a commit message' "$work/repo" base

new_repo
commit 'Generated by Some Tool' 'docs: add a note' 'Nothing special.'
expect fail 'generated-by line in a tracked file' "$work/repo" base

new_repo
commit 'plain text' 'docs: add a note' 'Generated-by: Some Tool'
expect fail 'generated-by trailer in a commit message' "$work/repo" base

new_repo
commit 'plain text' 'docs: add a note' 'Generated by Some Tool'
expect fail 'generated-by line in a commit message' "$work/repo" base

mkdir -p "$work/norepo"
expect fail 'outside a git repository' "$work/norepo"

if [ "$failures" -ne 0 ]; then
  echo "error: $failures hygiene test(s) failed" >&2
  exit 1
fi
